"""The competition protocol (rules.json): loading, and the README section generated from it.
Checking submissions and edits against it is the subnet project's job.

python -m wsp.rules doc     regenerate the protocol section of README.md from rules.json
"""
import re
import sys

from .common import REPO, read_json

RULES = read_json(REPO / "rules.json")


def doc():
    s, e, u = RULES["submission"], RULES["edit"], RULES["upload"]
    tracks = e["tracks"]
    rows = ["| limit | " + " | ".join(tracks) + " |", "|---|" + "---|" * len(tracks)]
    for key, label, fmt in (("max_tensors", "edited tensors", lambda v: "no limit" if v is None else str(v)),
                            ("max_payload_bytes", "payload", lambda v: f"{v // 1024} KiB"),
                            ("max_relative_change_per_tensor", "relative change per tensor", lambda v: f"{v:.0%}"),
                            ("max_global_relative_change", "global relative change", lambda v: f"{v:.0%}")):
        rows.append(f"| {label} | " + " | ".join(fmt(tracks[t][key]) for t in tracks) + " |")

    def files(d):
        return "\n".join(f"  - `{k}`: {v}" for k, v in d.items())

    return "\n".join([
        f"Protocol v{RULES['version']} (`rules.json`; generated by `python -m wsp.rules doc`). {RULES['about']}", "",
        f"**Submission (PR).** {s['about']} Directory `{s['path']}`:", files(s["files"]),
        f"  - file types {', '.join(s['allowed_extensions'])}; at most {s['max_total_bytes'] // 1024} KiB in total.", "",
        f"**Edit.** {e['about']}", f"- editable tensors: {e['editable_tensors']}",
        f"- ops: {', '.join(f'`{o}`' for o in e['ops'])}", f"- payload: {e['payload']}",
        f"- relative change: {e['relative_change']}", "", *rows, "",
        f"**Upload ({u['schema']}).** {u['about']}", files(u["files"]), f"- {u['manifest']}"])


def main():
    if sys.argv[1:] != ["doc"]:
        raise SystemExit(__doc__)
    readme = REPO / "README.md"
    block = f"<!-- protocol:begin -->\n{doc()}\n<!-- protocol:end -->"
    readme.write_text(re.sub(r"<!-- (rules|protocol):begin -->.*<!-- (rules|protocol):end -->", lambda _: block,
                             readme.read_text(), flags=re.S))


if __name__ == "__main__":
    main()
